package com.example.image

import java.io.File
import java.util.UUID

/**
 * A picture that was generated for a chat.
 *
 * The [token] is the short reference the text model writes into a reply or into
 * the HTML sandbox, for example `<img src="gen:1a2b3c4d5e6f">`.
 */
data class GeneratedImage(
    val id: String,
    val sessionId: String,
    val prompt: String,
    val width: Int,
    val height: Int,
    val createdAt: Long,
    val file: File
) {
    val token: String get() = tokenFor(id)

    companion object {
        /** The prefix that marks a reference to a generated picture. */
        const val PREFIX = "gen:"

        fun tokenFor(id: String): String = "$PREFIX$id"
    }
}

/**
 * Stores the pictures a chat generated, one folder per session.
 *
 * Pictures are per-chat files, not database rows: a chat that is deleted takes
 * its folder with it, and the text stays readable even when a picture is gone.
 * The names are random, so a reply can safely reference one without the model
 * ever seeing a path.
 */
class GeneratedImageStore(
    val rootDir: File
) {
    init {
        if (!rootDir.exists()) {
            rootDir.mkdirs()
        }
    }

    /** The folder that holds the pictures of [sessionId]. */
    fun sessionDir(sessionId: String): File = File(rootDir, sessionId)

    /**
     * Writes [png] into the session folder and returns the picture. A short
     * prompt is kept next to it so the gallery can describe what it shows.
     */
    fun save(
        sessionId: String,
        png: ByteArray,
        prompt: String,
        width: Int,
        height: Int
    ): GeneratedImage {
        val id = UUID.randomUUID().toString().replace("-", "").take(12)
        val dir = sessionDir(sessionId)
        dir.mkdirs()
        val file = File(dir, "$id.png")
        file.writeBytes(png)
        runCatching { File(dir, "$id.txt").writeText(prompt, Charsets.UTF_8) }
        return GeneratedImage(
            id = id,
            sessionId = sessionId,
            prompt = prompt,
            width = width,
            height = height,
            createdAt = System.currentTimeMillis(),
            file = file
        )
    }

    /** The picture file of [id], or null when it is unknown or gone. */
    fun fileFor(sessionId: String, id: String): File? {
        if (!isSafeId(id)) return null
        if (!isSafeSessionId(sessionId)) return null
        val file = File(sessionDir(sessionId), "$id.png")
        return if (file.isFile) file else null
    }

    /** The prompt that produced [id], or an empty string when there is none. */
    fun promptFor(sessionId: String, id: String): String {
        if (!isSafeId(id) || !isSafeSessionId(sessionId)) return ""
        val file = File(sessionDir(sessionId), "$id.txt")
        return if (file.isFile) runCatching { file.readText(Charsets.UTF_8) }.getOrDefault("") else ""
    }

    /** Every picture of [sessionId], oldest first. */
    fun list(sessionId: String): List<GeneratedImage> {
        if (!isSafeSessionId(sessionId)) return emptyList()
        val dir = sessionDir(sessionId)
        val files = dir.listFiles { file -> file.isFile && file.name.endsWith(".png") }
            ?: return emptyList()
        return files.sortedBy { it.name }.map { file ->
            val id = file.name.removeSuffix(".png")
            GeneratedImage(
                id = id,
                sessionId = sessionId,
                prompt = promptFor(sessionId, id),
                width = 0,
                height = 0,
                createdAt = file.lastModified(),
                file = file
            )
        }
    }

    /** A `data:` URI for [id], or null when the picture is gone. */
    fun dataUri(sessionId: String, id: String): String? {
        val file = fileFor(sessionId, id) ?: return null
        return "data:image/png;base64," + Base64Codec.encode(file.readBytes())
    }

    /** Removes every picture of [sessionId]. Called when the chat is deleted. */
    fun deleteSession(sessionId: String): Boolean {
        if (!isSafeSessionId(sessionId)) return false
        return sessionDir(sessionId).deleteRecursively()
    }

    /** Removes every picture the app stores. */
    fun deleteAll(): Boolean {
        val deleted = rootDir.deleteRecursively()
        rootDir.mkdirs()
        return deleted
    }

    companion object {
        /**
         * A picture id is generated by the app, so it only ever holds the
         * characters the random name is built from. Anything else is refused
         * so a forged reference cannot point outside the session folder.
         */
        fun isSafeId(id: String): Boolean =
            id.isNotEmpty() && id.length <= 64 && id.all { it.isLetterOrDigit() || it == '-' || it == '_' }

        /** Session ids are UUIDs, but a stricter check keeps paths predictable. */
        fun isSafeSessionId(sessionId: String): Boolean =
            sessionId.isNotEmpty() && sessionId.length <= 128 &&
                sessionId.all { it.isLetterOrDigit() || it == '-' || it == '_' }
    }
}
